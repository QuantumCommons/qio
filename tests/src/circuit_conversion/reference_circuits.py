"""Static, controlled input circuits for the conversion test battery.

Each :class:`ReferenceCircuit` wraps a single paradigm-specific ``spec``
(:class:`GateSpec`, :class:`AnalogSpec` or :class:`PhotonicSpec`) describing the
circuit once, in a declarative way; the SDK representations are generated by the
spec's own builders (``cirq``, ``qiskit``, ...) so the spec stays decoupled from
the SDKs. The envelope exposes the spec through retro-compatible accessors
(``n_qubits``, ``gates``, ``paradigm``, ...) and dispatches the builders.

- **Gate-based paradigm** (``paradigm="gate"``): a literal gate list with known
  ``n_qubits`` and, for deterministic circuits, known measurement counts. Built
  for Cirq, Qiskit, OpenQASM 2, OpenQASM 3 and CUDA-Q.
- **Analog paradigm** (``paradigm="analog"``): an :class:`AnalogSpec` describing
  an analog pulse schedule (atom register coordinates, declared channels,
  pulses per channel, optional measurement). Built as a Pulser ``Sequence``.
- **Photonic paradigm** (``paradigm="photonic"``): a :class:`PhotonicSpec`
  describing a mode-based photonic circuit (dual-rail qubits, beam splitters,
  phase shifters and native heralded CNOT blocks, input Fock state and herald
  post-selection). Built as a Perceval ``Circuit``.

The gate set is restricted to gates supported by all converters
(``qio/utils/conversion/program/*``), notably ``qasm3_to_cudaq`` and
``cirq.contrib.qasm_import``. It is deliberately representative:
single/multi qubit, parameterized gates, and measurements.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

# Gate parameters are usually floats; a symbolic parameter is encoded as the
# string marker "~<name>" so it flows through the op-chain comparison (see the
# ``parametrized`` circuit and the ``_*_operations`` helpers in
# ``circuit_testing``).
Param = Union[float, str]
Operation = Tuple[str, Tuple[Param, ...], Tuple[int, ...]]

_SUPPORTED_GATES = {
    "h",
    "x",
    "y",
    "z",
    "s",
    "t",
    "sdg",
    "tdg",
    "rx",
    "ry",
    "rz",
    "cx",
    "cz",
    "measure",
}

_PARAM_GATES = {"rx", "ry", "rz"}
_SINGLE_QUBIT_GATES = {
    "h",
    "x",
    "y",
    "z",
    "s",
    "t",
    "sdg",
    "tdg",
}
_TWO_QUBIT_GATES = {"cx", "cz"}


def _fmt(num: float) -> str:
    if isinstance(num, str):
        # Symbolic parameter marker "~<name>": emit the bare name.
        return num[1:] if num.startswith("~") else num
    return repr(float(num))


def _ops(*operations: Operation) -> List[Operation]:
    for gate, params, indices in operations:
        assert gate in _SUPPORTED_GATES, f"unsupported gate: {gate}"
        if gate in _PARAM_GATES:
            assert len(params) == 1, gate
        if gate in _SINGLE_QUBIT_GATES:
            assert len(indices) == 1, gate
        if gate in _TWO_QUBIT_GATES or gate == "measure":
            assert len(indices) >= 1, gate
    return list(operations)


# Programming-paradigm discriminator: each ReferenceCircuit belongs to one
# paradigm family (gate-based circuits, analog pulse schedules, photonic
# circuits) and only runs on the conversion edges of that same paradigm (see
# ``ConversionEdge.paradigm`` in ``circuit_testing`` and ``supports_edge``).
PARADIGM_GATE = "gate"
PARADIGM_ANALOG = "analog"
PARADIGM_PHOTONIC = "photonic"


@dataclass
class PulseSpec:
    """A single pulse on one channel of an analog schedule.

    ``kind`` describes the amplitude waveform shape ("constant" | "blackman").
    ``target`` is the qubit id (e.g. "q0") the pulse is addressed to - only
    meaningful on local-addressing channels, None on global channels.
    """

    channel: str
    kind: str
    duration: int
    amplitude: float
    detuning: float = 0.0
    phase: float = 0.0
    target: Optional[str] = None


@dataclass(frozen=True)
class PhotonicGate:
    """A single native block of a photonic circuit (paradigm="photonic").

    ``kind`` discriminates the Perceval component (and its mode placement):
    - ``"bs"``: a beam splitter on two modes ``modes`` with optional
      ``(theta, phi)`` parameters (empty params = 50/50 splitter);
    - ``"ps"``: a phase shifter ``PS(phi)`` on the single mode ``modes[0]``;
    - ``"heralded_cnot"``: the native Knill CNOT block (6 modes: control
      dual-rail ``(2*c, 2*c+1)``, data dual-rail ``(2*d, 2*d+1)``, ancilla at
      the end of the circuit ``(2*Q, 2*Q+1)``); ``qubits = (c, d)``.

    ``measure`` is left out of the spec: Perceval measures photon counts at the
    back-end, outside the Circuit (see ``PhotonicSpec.measure_qubits``).
    """

    kind: str
    modes: Tuple[int, ...] = ()
    params: Tuple[float, ...] = ()
    qubits: Tuple[int, ...] = ()


@dataclass
class GateSpec:
    """Declarative description of a gate-based circuit (paradigm="gate").

    ``gates`` is the canonical operation chain
    ``(name, params, qubit_indices)`` the converters must reproduce, so every
    SDK check compares against it. The circuit-level information
    (``global_phase`` / ``metadata`` / ``qubit_scheme``) and the runtime policy
    (``oracle``, ``supported_edge_ids``) live here too.
    """

    name: str
    n_qubits: int
    gates: Sequence[Operation]
    expected_counts: Optional[Dict[str, int]] = None
    description: str = field(default="")
    global_phase: float = field(default=0.0)
    metadata: Optional[Dict[str, Any]] = field(default=None)
    qubit_scheme: str = field(default="line")
    oracle: Optional[str] = field(default=None)
    supported_edge_ids: Optional[Tuple[str, ...]] = field(default=None)

    @property
    def paradigm(self) -> str:
        return PARADIGM_GATE

    def has_measurements(self) -> bool:
        return any(gate == "measure" for gate, _, _ in self.gates)

    def measurement_indices(self) -> List[int]:
        """Sorted qubit indices that receive a measurement."""
        return sorted(
            {i for gate, _, indices in self.gates if gate == "measure" for i in indices}
        )

    def topology_labels(self) -> Tuple[str, ...]:
        """Canonical (label, ...) the native Cirq builder produces for the
        declared ``qubit_scheme`` - used to detect topology losses."""
        if self.qubit_scheme == "line":
            return tuple(f"q{i}" for i in range(self.n_qubits))
        if self.qubit_scheme == "named":
            return tuple(chr(ord("a") + i) for i in range(self.n_qubits))
        if self.qubit_scheme == "grid":
            return tuple(f"(0,{i})" for i in range(self.n_qubits))
        raise ValueError(f"unknown qubit_scheme {self.qubit_scheme!r}")

    def cirq(self) -> "cirq.Circuit":
        import cirq

        if self.qubit_scheme == "line":
            qubits = cirq.LineQubit.range(self.n_qubits)
        elif self.qubit_scheme == "named":
            labels = self.topology_labels()
            qubits = [cirq.NamedQubit(label) for label in labels]
        elif self.qubit_scheme == "grid":
            qubits = [cirq.GridQubit(0, i) for i in range(self.n_qubits)]
        else:
            raise ValueError(f"unknown qubit_scheme {self.qubit_scheme!r}")
        operations = []
        for gate, params, indices in self.gates:
            targets = [qubits[i] for i in indices]
            if gate == "measure":
                # Distinct key per measurement so Cirq exports them to
                # distinct classical registers (a shared key collapses the
                # round trip: cirq writes every measurement to one bit).
                operations.append(
                    cirq.measure(*targets, key="m" + "".join(str(i) for i in indices))
                )
            elif gate in _PARAM_GATES:
                rads = params[0]
                if isinstance(rads, str):
                    import sympy

                    rads = sympy.Symbol(rads[1:] if rads.startswith("~") else rads)
                operations.append(getattr(cirq, gate)(rads).on(*targets))
            else:
                gate_obj = {
                    "h": cirq.H,
                    "x": cirq.X,
                    "y": cirq.Y,
                    "z": cirq.Z,
                    "s": cirq.S,
                    "t": cirq.T,
                    "sdg": cirq.S**-1,
                    "tdg": cirq.T**-1,
                    "cx": cirq.CNOT,
                    "cz": cirq.CZ,
                }[gate]
                operations.append(gate_obj(*targets))
        return cirq.Circuit(operations)

    def qiskit(self) -> "qiskit.QuantumCircuit":
        from qiskit import QuantumCircuit

        qc = QuantumCircuit(self.n_qubits, self.n_qubits, name=self.name)
        if self.global_phase:
            qc.global_phase = self.global_phase
        if self.metadata:
            qc.metadata = dict(self.metadata)
        for gate, params, indices in self.gates:
            targets = list(indices)
            if gate == "measure":
                for i in indices:
                    qc.measure(i, i)
            elif gate in _PARAM_GATES:
                param = params[0]
                if isinstance(param, str):
                    from qiskit.circuit import Parameter

                    param = Parameter(param[1:] if param.startswith("~") else param)
                getattr(qc, gate)(param, *targets)
            elif gate == "sdg":
                qc.sdg(*targets)
            elif gate == "tdg":
                qc.tdg(*targets)
            else:
                getattr(qc, gate)(*targets)
        return qc

    def qasm2(self) -> str:
        lines = [
            "OPENQASM 2.0;",
            'include "qelib1.inc";',
            f"qreg q[{self.n_qubits}];",
            f"creg c[{self.n_qubits}];",
        ]
        for gate, params, indices in self.gates:
            qargs = ", ".join(f"q[{i}]" for i in indices)
            if gate == "measure":
                for i in indices:
                    lines.append(f"measure q[{i}] -> c[{i}];")
                continue
            param_str = f"({', '.join(_fmt(p) for p in params)})" if params else ""
            lines.append(f"{gate}{param_str} {qargs};")
        return "\n".join(lines) + "\n"

    def qasm3(self) -> str:
        lines = [
            "OPENQASM 3.0;",
            'include "stdgates.inc";',
            f"qubit[{self.n_qubits}] q;",
            f"bit[{self.n_qubits}] c;",
        ]
        for gate, params, indices in self.gates:
            qargs = ", ".join(f"q[{i}]" for i in indices)
            if gate == "measure":
                for i in indices:
                    lines.append(f"c[{i}] = measure q[{i}];")
                continue
            param_str = f"({', '.join(_fmt(p) for p in params)})" if params else ""
            lines.append(f"{gate}{param_str} {qargs};")
        return "\n".join(lines) + "\n"

    def cudaq_kernel(self):
        import cudaq

        kernel = cudaq.make_kernel()
        qubits = kernel.qalloc(self.n_qubits)
        for gate, params, indices in self.gates:
            targets = [qubits[i] for i in indices]
            if gate == "measure":
                for q in targets:
                    kernel.mz(q)
            elif gate in _PARAM_GATES:
                param = params[0]
                if isinstance(param, str):
                    raise NotImplementedError(
                        "symbolic params are not representable in a CUDA-Q kernel"
                    )
                getattr(kernel, gate)(param, *targets)
            else:
                getattr(kernel, gate)(*targets)
        return kernel


@dataclass
class AnalogSpec:
    """Declarative description of an analog program (paradigm="analog").

    For now it encodes exactly the information needed to build a Pulser
    ``Sequence`` (``register_coords``, ``channels``, ``pulses``, ``measure``),
    see ``AnalogSpec.pulser``; the spec itself stays decoupled from Pulser and
    can later feed other analog SDKs.
    """

    name: str
    register_coords: List[Tuple[float, float]]
    channels: Dict[str, str]  # channel name -> pulser channel type ("rydberg_global", ...)
    pulses: List[PulseSpec]
    measure: bool = False
    description: str = field(default="")
    oracle: str = field(default="structural")

    @property
    def paradigm(self) -> str:
        return PARADIGM_ANALOG

    @property
    def n_qubits(self) -> int:
        return len(self.register_coords)

    @property
    def gates(self) -> List[Operation]:
        return []

    def has_measurements(self) -> bool:
        return self.measure

    def measurement_indices(self) -> List[int]:
        return list(range(self.n_qubits)) if self.measure else []

    def topology_labels(self) -> Tuple[str, ...]:
        return tuple(f"q{i}" for i in range(self.n_qubits))

    def pulser(self) -> "pulser.Sequence":
        """Builds the :class:`AnalogSpec` as a real Pulser ``Sequence``.

        The construction uses the minimal Pulser information carried by the
        spec: coordinates -> ``Register.from_coordinates``, channels ->
        ``declare_channel`` and pulses -> ``seq.add`` (local pulses target the
        atom id first). The :func:`pulser.Sequence.to_abstract_repr`
        serialization is Pulser's own canonical, device-independent
        representation, so an ``AnalogSpec`` and a round-tripped ``Sequence``
        can be compared by that representation.
        """
        from pulser import Pulse, Sequence
        from pulser.devices import MockDevice
        from pulser.register import Register
        from pulser.waveforms import BlackmanWaveform, ConstantWaveform

        register = Register.from_coordinates(self.register_coords, prefix="q")
        seq = Sequence(register, MockDevice)
        for channel, channel_type in self.channels.items():
            seq.declare_channel(channel, channel_type)
        for pulse_spec in self.pulses:
            if pulse_spec.target is not None:
                seq.target(pulse_spec.target, pulse_spec.channel)
            if pulse_spec.kind == "blackman":
                amp = BlackmanWaveform(pulse_spec.duration, pulse_spec.amplitude)
            else:
                amp = ConstantWaveform(pulse_spec.duration, pulse_spec.amplitude)
            seq.add(
                Pulse(
                    amp,
                    ConstantWaveform(pulse_spec.duration, pulse_spec.detuning),
                    pulse_spec.phase,
                ),
                pulse_spec.channel,
            )
        if self.measure:
            seq.measure()
        return seq


@dataclass
class PhotonicSpec:
    """Declarative description of a mode-based photonic circuit
    (paradigm="photonic").

    ``n_qubits`` is the number of dual-rail logical qubits (qubit ``q`` lives
    on modes ``(2q, 2q+1)``). ``gates`` is the ordered list of native blocks
    (beam splitters, phase shifters, *heralded CNOT*s, see
    :class:`PhotonicGate`). ``input_state`` is the Fock state feeding the
    circuit (mode -> photon count): it encodes the initial qubit logical state
    plus, for the heralded CNOT, the two ancilla photons on the trailing modes.
    ``heralds`` is the post-selection (mode -> required photon count) and
    ``measure_qubits`` the dual-rail qubits whose post-select counts form the
    output bitstring. The whole class is decoupled from Perceval (the SDK
    construction lives in :meth:`PhotonicSpec.perceval`).
    """

    name: str
    n_qubits: int
    gates: Sequence[PhotonicGate]
    input_state: Tuple[int, ...]
    measure_qubits: Tuple[int, ...] = ()
    heralds: Dict[int, int] = field(default_factory=dict)
    description: str = field(default="")
    oracle: str = field(default="photonic")

    @property
    def paradigm(self) -> str:
        return PARADIGM_PHOTONIC

    @property
    def n_modes(self) -> int:
        return len(self.input_state)

    def has_measurements(self) -> bool:
        return len(self.measure_qubits) > 0

    def measurement_indices(self) -> List[int]:
        return sorted(set(self.measure_qubits))

    def topology_labels(self) -> Tuple[str, ...]:
        return tuple(f"m{i}" for i in range(self.n_modes))

    def perceval(self) -> "perceval.Circuit":
        """Builds the spec as a real Perceval ``Circuit`` over ``n_modes``.

        Native components only: 50/50 beam splitters / parametrized
        ``BS(theta, phi)``, phase shifters ``PS(phi)`` and the native Knill
        heralded CNOT block (``HeraldedCnotItem``, control dual-rail on
        ``(2*c, 2*c+1)``, data on ``(2*d, 2*d+1)``, ancilla at the end of the
        circuit). ``measure`` is left out: the backend samples photon counts
        out of the circuit (see the ``"photonic"`` oracle in
        ``photonic_paradigm``).
        """
        from perceval import Circuit
        from perceval.components import BS, PS
        from perceval.components.core_catalog import HeraldedCnotItem

        qc = Circuit(self.n_modes, name=self.name)
        for gate in self.gates:
            if gate.kind == "bs":
                qc.add(gate.modes, BS(*gate.params))
            elif gate.kind == "ps":
                qc.add(gate.modes, PS(*gate.params))
            elif gate.kind == "heralded_cnot":
                control, data = gate.qubits
                ancilla = 2 * self.n_qubits
                cnot = HeraldedCnotItem().build_circuit()
                qc.add(
                    (2 * control, 2 * control + 1, 2 * data, 2 * data + 1, ancilla, ancilla + 1),
                    cnot,
                    merge=True,
                )
            else:
                raise NotImplementedError(f"unsupported photonic block: {gate.kind}")
        return qc


class ReferenceCircuit:
    """A static, controlled input circuit: a paradigm-specific ``spec`` (one of
    ``GateSpec`` / ``AnalogSpec`` / ``PhotonicSpec``) plus the retro-compatible
    accessors and SDK builders shared by every paradigm.

    The battery treats these circuits as trusted inputs (they are built
    statically and not checked), so the SDK builders here are only required to
    produce faithful representations of the spec.
    """

    def __init__(self, spec: Union[GateSpec, AnalogSpec, PhotonicSpec]):
        self.spec = spec

    # -- retro-compatible accessors (spec-unified) ----------
    @property
    def name(self) -> str:
        return self.spec.name

    @property
    def paradigm(self) -> str:
        return self.spec.paradigm

    @property
    def n_qubits(self) -> int:
        return self.spec.n_qubits

    @property
    def gates(self):
        return self.spec.gates

    @property
    def expected_counts(self) -> Optional[Dict[str, int]]:
        return getattr(self.spec, "expected_counts", None)

    @property
    def description(self) -> str:
        return getattr(self.spec, "description", "")

    @property
    def global_phase(self) -> float:
        return getattr(self.spec, "global_phase", 0.0)

    @property
    def metadata(self) -> Optional[Dict[str, Any]]:
        return getattr(self.spec, "metadata", None)

    @property
    def qubit_scheme(self) -> str:
        return getattr(self.spec, "qubit_scheme", "line")

    @property
    def oracle(self) -> Optional[str]:
        return getattr(self.spec, "oracle", None)

    @property
    def supported_edge_ids(self) -> Optional[Tuple[str, ...]]:
        return getattr(self.spec, "supported_edge_ids", None)

    @property
    def analog(self) -> Optional[AnalogSpec]:
        return self.spec if self.paradigm == PARADIGM_ANALOG else None

    @property
    def photonic(self) -> Optional[PhotonicSpec]:
        return self.spec if self.paradigm == PARADIGM_PHOTONIC else None

    @property
    def n_modes(self) -> Optional[int]:
        """Total mode count of a photonic circuit (None for other paradigms)."""
        return getattr(self.spec, "n_modes", None)

    # -- paradigm-independent helpers ----------------------------------
    def supports_edge(self, edge) -> bool:
        if edge.paradigm != self.paradigm:
            return False
        if self.supported_edge_ids is not None:
            return edge.id in self.supported_edge_ids
        return True

    def has_measurements(self) -> bool:
        return self.spec.has_measurements()

    def measurement_indices(self) -> List[int]:
        return self.spec.measurement_indices()

    def topology_labels(self) -> Tuple[str, ...]:
        return self.spec.topology_labels()

    # -- SDK builders (dispatched to the paradigm-specific spec) -------
    def cirq(self) -> "cirq.Circuit":
        return self.spec.cirq()

    def qiskit(self) -> "qiskit.QuantumCircuit":
        return self.spec.qiskit()

    def qasm2(self) -> str:
        return self.spec.qasm2()

    def qasm3(self) -> str:
        return self.spec.qasm3()

    def cudaq_kernel(self):
        return self.spec.cudaq_kernel()

    def pulser(self) -> "pulser.Sequence":
        return self.spec.pulser()

    def perceval(self) -> "perceval.Circuit":
        return self.spec.perceval()

    def __repr__(self) -> str:
        return f"ReferenceCircuit({self.name!r}, paradigm={self.paradigm!r})"
